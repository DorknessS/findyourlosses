@app.route("/items")
@login_required
def items():
    ensure_db()
    keyword = request.args.get("q", "").strip()
    con = connect()
    try:
        with con.cursor() as cur:
            if keyword:
                k = f"%{keyword}%"
                cur.execute(
                    """
                    SELECT id, item_type, title, category, location, date_found_lost, status
                    FROM items
                    WHERE title ILIKE %s OR category ILIKE %s OR location ILIKE %s
                    ORDER BY id DESC
                    """,
                    (k, k, k),
                )
            else:
                cur.execute(
                    """
                    SELECT id, item_type, title, category, location, date_found_lost, status
                    FROM items ORDER BY id DESC
                    """
                )
            rows = cur.fetchall()
    finally:
        con.close()
    return render_template("items.html", items=rows, keyword=keyword)


@app.route("/items/<int:item_id>")
@login_required
def item_detail(item_id):
    ensure_db()
    con = connect()
    try:
        with con.cursor() as cur:
            cur.execute(
                """
                SELECT items.*, users.fullname
                FROM items
                JOIN users ON users.id = items.user_id
                WHERE items.id=%s
                """,
                (item_id,),
            )
            item = cur.fetchone()
    finally:
        con.close()

    if not item:
        flash("ไม่พบรายการนี้", "danger")
        return redirect(url_for("items"))
    return render_template("item_detail.html", item=item)


