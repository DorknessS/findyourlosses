import os
import sqlite3
from datetime import datetime
from functools import wraps

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:  # Optional for local SQLite-only development. Vercel installs it from requirements.txt.
    psycopg = None
    dict_row = None
from flask import Flask, flash, redirect, render_template, request, session, url_for
from werkzeug.security import check_password_hash, generate_password_hash

app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "dev-only-change-this-secret-key")

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SQLITE_DB = os.path.join(BASE_DIR, "lost_found.db")
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()


class DatabaseConnection:
    """Small compatibility wrapper so the app works with SQLite locally and Postgres on Vercel."""

    def __init__(self):
        self.is_postgres = bool(DATABASE_URL)
        if self.is_postgres:
            if psycopg is None:
                raise RuntimeError("psycopg is required when DATABASE_URL is set.")
            self.con = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        else:
            self.con = sqlite3.connect(SQLITE_DB)
            self.con.row_factory = sqlite3.Row

    def execute(self, query, params=()):
        if self.is_postgres:
            query = query.replace("?", "%s")
        return self.con.execute(query, params)

    def cursor(self):
        return self.con.cursor()

    def commit(self):
        self.con.commit()

    def rollback(self):
        self.con.rollback()

    def close(self):
        self.con.close()


def connect():
    return DatabaseConnection()


def init_db():
    con = connect()
    try:
        if con.is_postgres:
            con.execute("""
                CREATE TABLE IF NOT EXISTS users(
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL,
                    fullname TEXT NOT NULL,
                    phone TEXT
                )
            """)
            con.execute("""
                CREATE TABLE IF NOT EXISTS items(
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    item_type TEXT NOT NULL,
                    title TEXT NOT NULL,
                    category TEXT,
                    description TEXT,
                    location TEXT,
                    date_found_lost TEXT,
                    contact TEXT,
                    status TEXT DEFAULT 'เปิดประกาศ',
                    created_at TEXT NOT NULL,
                    FOREIGN KEY(user_id) REFERENCES users(id)
                )
            """)
        else:
            con.execute("""
                CREATE TABLE IF NOT EXISTS users(
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    username TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL,
                    fullname TEXT NOT NULL,
                    phone TEXT
                )
            """)
            con.execute("""
                CREATE TABLE IF NOT EXISTS items(
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    user_id INTEGER NOT NULL,
                    item_type TEXT NOT NULL,
                    title TEXT NOT NULL,
                    category TEXT,
                    description TEXT,
                    location TEXT,
                    date_found_lost TEXT,
                    contact TEXT,
                    status TEXT DEFAULT 'เปิดประกาศ',
                    created_at TEXT NOT NULL,
                    FOREIGN KEY(user_id) REFERENCES users(id)
                )
            """)
        con.commit()
    finally:
        con.close()


# Vercel imports app.py rather than running it as __main__, so initialize the
# persistent database when the function instance starts.
init_db()


def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if "user_id" not in session:
            return redirect(url_for("login"))
        return view(*args, **kwargs)

    return wrapped


