@app.route("/login", methods=["GET", "POST"])
def login():
    ensure_db()
    if request.method == "POST":
        username = request.form["username"].strip()
        password = request.form["password"]
        con = connect()
        try:
            with con.cursor() as cur:
                cur.execute(
                    "SELECT id, username, password, fullname, phone FROM users WHERE username=%s",
                    (username,),
                )
                user = cur.fetchone()
        finally:
            con.close()
        if user and check_password_hash(user["password"], password):
            session["user_id"] = user["id"]
            session["fullname"] = user["fullname"]
            return redirect(url_for("home"))
        flash("ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง", "danger")
    return render_template("login.html")


@app.route("/register", methods=["GET", "POST"])
def register():
    ensure_db()
    if request.method == "POST":
        username = request.form["username"].strip()
        password = request.form["password"]
        fullname = request.form["fullname"].strip()
        phone = request.form["phone"].strip()

        if not username or not password or not fullname:
            flash("กรุณากรอกข้อมูลที่จำเป็น", "warning")
            return render_template("register.html")

        con = connect()
        try:
            with con.cursor() as cur:
                cur.execute(
                    """
                    INSERT INTO users(username, password, fullname, phone)
                    VALUES(%s, %s, %s, %s)
                    """,
                    (username, generate_password_hash(password), fullname, phone),
                )
            con.commit()
            flash("สมัครสมาชิกเรียบร้อยแล้ว", "success")
            return redirect(url_for("login"))
        except errors.UniqueViolation:
            con.rollback()
            flash("ชื่อผู้ใช้นี้มีอยู่แล้ว", "danger")
        finally:
            con.close()
    return render_template("register.html")


